using System.Collections.Immutable;
using System.Text;
using BenchmarkDotNet.Attributes;
using Microsoft.CodeAnalysis;
using Purview.Telemetry.SourceGenerator.Emitters;
using Purview.Telemetry.SourceGenerator.Helpers;
using Purview.Telemetry.SourceGenerator.Records;

namespace Purview.Telemetry.SourceGenerator.Benchmarks;

[MemoryDiagnoser]
public class FullGenerationBenchmarks
{
    [Params(5, 25, 75)]
    public int Methods;

    MultiTargetGenerationTarget _target = null!;

    [GlobalSetup]
    public void Setup()
    {
        var methods = ImmutableArray.CreateBuilder<MultiTargetMethod>();
        for (int i = 0; i < Methods; i++)
        {
            var cfg = new MultiTargetConfiguration(
                IsMultiTargetEnabled: true,
                TargetTypes: GenerationType.Activities
                    | GenerationType.Logging
                    | GenerationType.Metrics,
                ActivityName: $"Op{i}",
                LogMessage: $"Operation {i} executed",
                LogLevel: "Information",
                LogEventId: i
            );
            methods.Add(
                new MultiTargetMethod(
                    $"Op{i}",
                    $"Namespace.IOp{i}",
                    MethodSymbol: null!,
                    Configuration: cfg,
                    Parameters: ImmutableArray<MultiTargetParameter>.Empty,
                    Location: Location.None
                )
            );
        }
        var telemetryAttr = new TelemetryGenerationAttributeRecord(
            GenerateDependencyExtension: new(false),
            ClassName: new("Gen"),
            DependencyInjectionClassName: new("GenExtensions"),
            DependencyInjectionClassIsPublic: new(true)
        );
        _target = new MultiTargetGenerationTarget(
            TelemetryGeneration: telemetryAttr,
            GenerationType: GenerationType.Activities
                | GenerationType.Logging
                | GenerationType.Metrics,
            ClassNameToGenerate: "Gen",
            ClassNamespace: "Bench",
            ParentClasses: System.Array.Empty<string>(),
            FullNamespace: "Bench",
            FullyQualifiedName: "Bench.Gen",
            InterfaceType: Constants.Empty,
            Methods: methods.ToImmutable(),
            DuplicateMethods: ImmutableDictionary<string, Location[]>.Empty,
            Failures: null
        );
    }

    [Benchmark]
    public string LegacyBuilder()
    {
        return LegacyMultiTargetGenerator.Generate(_target);
    }

    [Benchmark]
    public string CodeWriterAdapter()
    {
        return MultiTargetClassEmitter.GenerateForBenchmark(_target);
    }
}

static class LegacyMultiTargetGenerator
{
    // Minimal approximation of pre-CodeWriter path (StringBuilder based)
    public static string Generate(MultiTargetGenerationTarget target)
    {
        var sb = new StringBuilder();
        // Header (mirrors current header structure without timestamp scrub)
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//\tThis code was generated by the Purview.Telemetry.SourceGenerator");
        sb.AppendLine("//\ton {DateTime}.");
        sb.AppendLine("//");
        sb.AppendLine("//\tChanges to this file may cause incorrect behaviour and will be lost");
        sb.AppendLine("//\twhen the code is regenerated.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine(
            "#pragma warning disable 1591 // publicly visible type or member must be documented"
        );
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        if (!string.IsNullOrWhiteSpace(target.ClassNamespace))
        {
            sb.Append("namespace ").Append(target.ClassNamespace).AppendLine();
            sb.AppendLine("{");
        }
        // Class attributes (mirrors generator attributes)
        sb.AppendLine("\t[global::System.Runtime.CompilerServices.CompilerGenerated]");
        sb.AppendLine(
            "\t[global::System.CodeDom.Compiler.GeneratedCode(\"Purview.Telemetry.SourceGenerator\", \"0.1.0.0\")] "
        );
        sb.AppendLine(
            "\t[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]"
        );
        sb.AppendLine("\t[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        sb.AppendLine("\tsealed partial class " + target.ClassNameToGenerate);
        sb.AppendLine("\t{");
        // Simulate method emission cost proportional to Methods count
        foreach (var method in target.Methods)
        {
            sb.Append('\t').Append("void ").Append(method.MethodName).AppendLine("() {}");
        }
        sb.AppendLine("\t}");
        if (!string.IsNullOrWhiteSpace(target.ClassNamespace))
            sb.AppendLine("}");
        return sb.ToString();
    }
}
