using System.Globalization;
using System.Reflection;
using System.Text;

namespace Purview.Telemetry.SourceGenerator.Templates;

sealed class EmbeddedResources
{
	readonly Assembly _ownerAssembly = typeof(EmbeddedResources).Assembly;
	readonly string _namespaceRoot = typeof(EmbeddedResources).Namespace;

	// Make sure this is above any calls to LoadTemplateForEmitting.
	readonly string _autoGeneratedHeader;

	EmbeddedResources()
	{
		_autoGeneratedHeader = LoadEmbeddedResource("AutoGeneratedHeader.cs");
	}

	public static EmbeddedResources Instance { get; } = new();

	string LoadEmbeddedResource(string resourceName)
	{
		resourceName = $"{_namespaceRoot}.Sources.{resourceName}";

		var resourceStream = _ownerAssembly.GetManifestResourceStream(resourceName);
		if (resourceStream is null)
		{
			var existingResources = _ownerAssembly.GetManifestResourceNames();
			throw new ArgumentException(
				$"Could not find embedded resource {resourceName}. Available resource names: {string.Join(", ", existingResources)}"
			);
		}

		using StreamReader reader = new(resourceStream, Encoding.UTF8);
		var result = reader.ReadToEnd();

		result = result.Replace(
			"{CodeGen}",
			Constants.System.GeneratedCode.Value + "\n[global::Microsoft.CodeAnalysis.Embedded]"
		);

		return result.Trim();
	}

	/// <param name="text">The text to which the header will be added.</param>
	/// <param name="emitNullable">
	/// true = unconditional <c>#nullable enable</c>, false = omit, null = conditional on
	/// <c>NET48_OR_GREATER || PURVIEW_TELEMETRY_NON_NULLABLE</c> (for injected template files).
	/// </param>
	public string AddHeader(string text, bool? emitNullable = true)
	{
		const string nullableGuard =
			"#if !NET48_OR_GREATER && !PURVIEW_TELEMETRY_NON_NULLABLE\n#nullable enable\n#endif";

		string nullableSection = emitNullable switch
		{
			true => "#nullable enable\n\n",
			false => string.Empty,
			null => nullableGuard + "\n\n",
		};

		var result =
			_autoGeneratedHeader.Replace(
				"{DateTime}",
				DateTimeOffset.UtcNow.ToString("yyyy-MM-dd HH:mm:ss zzzz", CultureInfo.InvariantCulture)
			)
			+ "\n\n"
			+ nullableSection
			+ text.Trim();

		return result + "\n";
	}

	public string LoadTemplateForEmitting(string? source, string name, bool attachHeader = true)
	{
		source = source == null ? null : source + ".";

		var resource = LoadEmbeddedResource($"{source}{name}.cs");
		return attachHeader ? AddHeader(resource, emitNullable: null) : resource;
	}
}
